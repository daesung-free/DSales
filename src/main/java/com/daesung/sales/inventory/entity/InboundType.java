package com.daesung.sales.inventory.entity;

/**
 * 입고구분. 근거: 요구사항정의서 8p 입고/대체등록 [정정 2026-07-28 재무팀].
 * 순매출조회(16p)의 외부콘텐츠 매입액은 PURCHASE(매입입고)로 등록된 입고만 집계한다
 * (NORMAL=인쇄소 등 자체 제작 입고는 매입원가에서 제외).
 */
public enum InboundType {
    /** 정상입고(인쇄소 등 자체 제작·조달). 매입원가에 포함되지 않음. */
    NORMAL,
    /** 매입입고(외부콘텐츠 자회사 직거래 매입). 16p 순매출조회 매입 데이터로 자동 연결. */
    PURCHASE,
    /**
     * 반품입고(거래처에서 되돌아온 물량).
     *
     * <p>‼️<b>매입액 집계에 들어가지 않는다.</b> 반품으로 들어온 물건은 사 온 게 아니다 —
     * 순매출조회(16p) 매입액은 {@link #PURCHASE}만 센다.
     *
     * <p>★매출 반품까지 한 번에 처리하려면 {@code POST /sales/return-inbound}를 쓴다.
     * 이 구분값은 <b>입고 화면에서 "반품으로 들어온 입고"라고 표시</b>하기 위한 것이다
     * (2026-09-17 피드백 화면5 — 드롭다운에 반품입고가 없다).
     */
    RETURN,
    /**
     * 매입반품(사 온 물건을 공급처로 되돌려 보냄).
     *
     * <p>근거: 발주처 1차회신(2026-10-02) #6 "매입반품 실제 발생".
     * ‼️정본 16p 인터뷰(2026-07-25)가 "연말 일괄, 연중 반품 없음"으로 닫아 두었던 것을
     * 발주처가 직접 뒤집었다 — 그 근거로 칸을 안 만든 판단은 더 이상 유효하지 않다.
     *
     * <p>★<b>매입의 역이라 같은 INBOUND 축에 둔다.</b> 매출·출고가 아니다 —
     * 그래야 정본 16p 의 "입고 / 매입반품 / 매입액" 세 칸이 한 축에서 나온다.
     * <b>수량은 음수로 저장</b>한다(재고가 실제로 줄어든다). 화면은 양수로 입력하고
     * 서버가 뒤집는다 — 폐기와 같은 규칙이다.
     *
     * <p>‼️<b>매입액(단가·이익) 집계에는 넣지 않는다.</b> 매입액은 "판 물건을 얼마에 사 왔나"고,
     * 매입반품은 재고 흐름이다. 섞으면 반품한 달의 이익률이 실제와 달라진다.
     */
    PURCHASE_RETURN
}
