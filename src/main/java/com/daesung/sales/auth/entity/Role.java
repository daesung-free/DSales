package com.daesung.sales.auth.entity;

/**
 * 직원 역할(RBAC). 근거: 발주처 「사용자권한_구조_설계_예시(수정)」 —
 * "역할 4종(관리자/영업/물류/재무)".
 *
 * <p>★<b>조회전용(VIEWER)은 없앴다.</b> 발주처 원문:
 * "조회전용 역할은 제외했습니다 — 3단계 구조 자체가 특정 사용자에게 특정 화면의
 * 조회 권한만 개별로 부여할 수 있어, 별도 역할로 두지 않아도 동일한 효과를 낼 수 있습니다."
 * 실제로 화면 권한을 전부 ◐(READ)로 준 역할이 곧 조회전용이다.
 *
 * <p>역할이 할 수 있는 일은 이 enum이 아니라 <b>권한 표</b>(V52)가 정한다.
 */
public enum Role {
    /** 관리자 */
    ADMIN,
    /** 재무 */
    FINANCE,
    /** 물류 */
    LOGISTICS,
    /** 영업 */
    SALES
}
