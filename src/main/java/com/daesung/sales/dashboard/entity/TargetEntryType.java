package com.daesung.sales.dashboard.entity;

/**
 * 목표표에 담기는 값의 종류.
 *
 * <p>{@link #ACTUAL}이 필요한 이유: 레거시 데이터를 이관하지 않기로 해서 과거연도 매출이 우리 DB에 없다.
 * 그런데 자료요청서 1-6에서 "2026년 목표와 2025년 실적만 주시면 비교 그래프까지 정상 표시"라고
 * 요청했고 발주처도 그렇게 보냈다 — 그 실적을 저장해둬야 전년비가 나온다.
 * 우리 매출 데이터가 쌓인 연도는 DB에서 계산하고, 없는 과거연도만 이 값으로 채운다.
 */
public enum TargetEntryType {
    /** 목표(예산) */
    TARGET,
    /** 확정 실적 — 이관하지 않은 과거연도 보관용 */
    ACTUAL
}
