-- 계산서 **작성일자 수정**(현장 피드백 2026-10-14 B-6).
--   원문: "작성일자는 일괄로 말일에 맞춰서 나온다 → 보이는 것만 수정하기"
--
-- 지금 작성일자는 조회 종료일로 고정이라 바꿀 칸이 없다.
--
-- ★기존 `issue_date` 는 **어느 계산서인지 가리키는 키**라 바꾸면 안 된다.
--   그 값을 고치면 보정 자체를 다시 못 찾는다(그 날짜로 조회해야 붙는다).
--   그래서 '표시할 날짜'를 **별도 컬럼**으로 둔다 — 키는 그대로, 보여주는 값만 바뀐다.
ALTER TABLE tax_invoice_adjustment
    ADD COLUMN new_issue_date DATE NULL
        COMMENT '작성일자 보정 — 조회·엑셀에 이 날짜로 나간다. NULL 이면 조회 종료일 그대로';
