-- 도서 기본정보 '공급률'. 근거: 정본 구분값정리 [6.도서관리-1.기본정보]
--   "Web/신청사이트 연동 및 매출 항목(신규) | 정가 / 공급률 | 판매가 계산 기준"
-- 자료요청서 1-2 공급률표도 "거래처구분별 대표값"만 받았고 전 거래처 매핑은 오지 않았다.
--
-- ★공급률이 두 군데 있는 이유(중복이 아니다)
--   · product.supply_rate          = 도서 자체의 기본 공급률(거래처 매핑이 없을 때 쓰는 바탕값)
--   · product_partner_price.supply_rate = 그 거래처에만 적용되는 예외값(V19)
--   매출등록 자동적용 우선순위: 입력값 > 거래처별 매핑 > 도서 기본값.
--   지금까지는 거래처 매핑이 없으면 곧바로 오류였는데, 발주처가 대표값만 주는 운영이라
--   바탕값이 없으면 매핑을 전 거래처×전 도서로 깔아야 등록이 된다.

ALTER TABLE products
    ADD COLUMN supply_rate INT NULL
        COMMENT '기본 공급률(%). 거래처별 매핑이 없을 때 적용되는 바탕값. 미입력이면 매핑 필수';
