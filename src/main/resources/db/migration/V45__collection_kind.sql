-- 수금관리(23p) 수금구분 신설. 근거: 정본 23p 「주요 데이터 항목」
--   수금일자, 기장일자, 거래처명, **수금구분**, **입금구분**, 금액, 어음번호, 만기일자, 은행/지점명, 비고
--
-- ★두 축의 정체(레거시 실측 — 수금등록.vb:61~62)
--     collKind as '수금구분',
--     collType as '입금구분',
--   우리가 갖고 있던 coll_type이 **입금구분**(현금/어음/선수금/대체)이고, 이름만 '수금유형'으로
--   잘못 달려 있었다. 없던 축은 수금구분이다.
--
-- ★수금구분은 레거시에서 사실상 상수다
--   수금등록.vb:19~20 —
--     TextBox_CollKind.Text = "도서대금"
--     TextBox_CollKind.ReadOnly = True
--   화면에서 "도서대금"으로 고정하고 편집을 막아 놨으며, 저장된 값을 되읽는 코드는 주석 처리돼 있다(81·107행).
--   그래서 기본값을 "도서대금"으로 두되 컬럼은 열어 둔다 — 정본이 데이터 항목으로 명시한 이상
--   재무팀이 다른 명목(예: 연체이자)으로 수금할 여지를 막을 이유가 없다.
--   ⚠️값 목록을 우리가 지어내지 않는다. 관리형 목록이 필요하다면 발주처 확인 후 마스터로 올린다.

ALTER TABLE collection
    ADD COLUMN coll_kind VARCHAR(30) NOT NULL DEFAULT '도서대금'
        COMMENT '수금구분(무슨 명목으로 받은 돈인가). 레거시 collKind — 화면에서 "도서대금" 고정이었다';

-- 수금구분·입금구분으로 거르는 조회(23p 그리드 필터)
CREATE INDEX ix_collection_kind ON collection (coll_kind, coll_date);
