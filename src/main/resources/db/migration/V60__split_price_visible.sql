-- '수불부/단가 노출' 한 필드를 **둘로 나눈다**.
--
-- ★배경: 33p 화면기획안 컬럼명이 「수불부/단가 노출(Y/N)」 하나였고, 우리는 그대로
--   `products.ledger_visible`(V17) 한 값으로 구현했다. 프론트가 지적했다(회신 2026-08-21 E-7) —
--   "한 필드에 **두 가지 뜻**이 실립니다".
--
-- ★두 판단은 실제로 다르다
--     수불부 노출 : 제품수불부(11p) 집계에 포함할지.
--                  DSRE에서 수불을 관리하는 상품은 우리 수불부에서 빼야 한다.
--     단가 노출   : 거래처별 단가(34p) 화면에 이 도서를 띄울지.
--                  단가를 거래처별로 매기지 않는 상품(모의고사 등)은 그 화면에서 빠져야 한다.
--   같은 상품이 "수불부엔 안 나오지만 단가는 매긴다"일 수 있다. 한 값으로는 표현이 안 된다.
--
-- ★기존 값은 그대로 옮긴다(price_visible = ledger_visible).
--   나누는 것이 목적이지 판정을 바꾸는 게 아니다. 지금까지 Y였던 상품이 갑자기
--   단가 화면에서 사라지면, 나눈 것이 아니라 망가뜨린 것이다.

ALTER TABLE products
    ADD COLUMN price_visible BOOLEAN NOT NULL DEFAULT TRUE
        COMMENT '단가노출 — 거래처별 단가(34p) 화면 노출 여부. 수불부노출과 별개 축';

UPDATE products SET price_visible = ledger_visible;
