-- 공통 자재의 **회차 반복 여부**. 근거: 발주처 「도서관리·제품수불부현황 데이터 구조 보완 요청안」
-- (2026-08-31) 각주 원문 —
--   "세트당 소요수량은 '공통' 매칭 자재도 세트 내 **회차 반복 여부를 고려한 최종 수량**으로
--    입력합니다 — 회차마다 반복 사용되는 자재(예: OMR, 위 표는 **4회차 구성 기준 4**)는
--    **회차 수만큼 반영한 값**을, 세트 전체에 한 번만 필요한 자재(예: 해설강의쿠폰)는
--    **1로 고정**한 값을 입력합니다."
--
-- ★문서는 공통 자재를 **두 종류**로 나눠 놓았는데, 우리 스키마엔 그 구분을 담을 자리가 없었다.
--   qty_per_set 숫자 하나만 보고는 `4`가
--     ① 4회차 × 회차당 1  (OMR — 반복형)
--     ② 세트당 4개 고정    (반복 없음)
--   중 어느 쪽인지 알 수 없다. 그래서 "회차만 단독으로 팔렸을 때 공통 자재가 몇 장 나갔나"를
--   역산할 수 없어 제품수불부 자재 상세에서 **0으로 비워 두고 있었다**.
--
-- ★기존 행은 전부 FALSE(=1회형)로 둔다. 지금 동작이 0이므로 **값을 그대로 옮기는 것**이다.
--   여기서 "qty_per_set > 1 이면 반복형" 같은 추측으로 채우면, 세트당 4개 고정인 자재가
--   갑자기 회차마다 나간 것으로 잡혀 **없던 소요량이 생긴다**. 켜는 것은 담당자가 할 일이다.

ALTER TABLE material_bom
    ADD COLUMN per_round BOOLEAN NOT NULL DEFAULT FALSE
        COMMENT '회차 반복형 여부(공통 자재 전용). TRUE=회차마다 반복 사용(OMR 등, 회차당 소요=세트당수량÷회차수) / FALSE=세트 전체에 한 번(쿠폰 등)';
