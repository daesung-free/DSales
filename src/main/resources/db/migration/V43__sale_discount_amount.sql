-- 매출 라인에 적용된 할인액 기록. 근거: 정본 34p 데이터 항목 '할인액' +
-- 레거시 매출가져오기.vb:425 `단가 = if(할인액 > 0, 정가-할인액, 정가*공급률/100)`.
--
-- ★왜 매출에 저장하나
--   할인액은 거래처×대분류 매핑(V42)에서 온다. 그런데 그 매핑은 담당자가 언제든 고친다.
--   매출에 남겨두지 않으면 "이 건의 금액이 왜 이 값인가"를 나중에 설명할 수 없다
--   (정가·공급률을 이미 같은 이유로 매출에 복사해 두고 있다).
--
-- ★할인액이 있으면 공급률은 금액에 쓰이지 않는다
--   레거시 식이 둘 중 하나만 쓴다. 둘 다 곱하면 이중 할인이 된다.
--   supply_rate 컬럼은 그대로 채워 두되(참고값), 금액은 정가−할인액 기준이다.

ALTER TABLE sales
    ADD COLUMN discount_amount INT NULL
        COMMENT '적용된 권당 할인액(34p). 값이 있으면 공급가액 = (정가-할인액)×수량';
