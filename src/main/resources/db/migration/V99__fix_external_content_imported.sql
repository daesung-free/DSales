-- 이감 외부콘텐츠(S2026Y02) 26종의 **콘텐츠구분·세부구분 정정**.
--
-- ★ 무엇이 틀렸나 (프론트 실측 2026-10-23 §6① · 발주처 확정)
--   이관 스크립트가 콘텐츠구분을 **전부 'SELF'(자체교재)로 박아** 넣었고,
--   세부구분은 분류코드 첫 글자 규칙('S' → 기타고사)으로 채웠다.
--   그런데 이 분류는 이름 그대로 '2026 외부콘텐츠(이감)' 이다 —
--   발주처 확정값은 **외부콘텐츠 · 기타** 다.
--
-- ★ 왜 중요한가(표기만의 문제가 아니다)
--   순매출조회가 콘텐츠구분으로 갈린다 — 외부콘텐츠는 매입원가(매입입고 unit_cost 평균)를
--   빼서 이익률을 낸다. 자체교재로 두면 **매입이 통째로 빠져 이익이 부풀어 보인다.**
--   이감은 실제로 매입이 발생하는 외부 콘텐츠다(정본 §5 "외부는 매입 발생 → 순매출=매출−매입").
--
-- ★ 범위를 좁게 잡는 이유
--   분류명에 '외부콘텐츠'가 든 것을 전부 바꾸면 앞으로 들어올 연도분까지 자동으로 걸리지만,
--   발주처가 확정한 것은 **S2026Y02 26종**뿐이다. 추론으로 범위를 넓히지 않는다.
--   (같은 문제가 다음 연도에 생기면 그때 같은 모양으로 한 줄 더 쓴다.)
--
-- ★ 담당자가 이미 고친 행은 건드리지 않는다
--   틀린 값(SELF)인 것만 바꾼다. 여러 번 돌려도 같다.
--   시험 서버는 화면 담당이 API로 이미 26건을 정정했고, 그쪽은 이 UPDATE 에 안 걸린다.

UPDATE products
   SET content_type = 'EXTERNAL'
 WHERE cat_code = 'S2026Y02'
   AND content_type = 'SELF';

-- 세부구분 — '기타고사'는 분류코드 첫 글자('S') 규칙이 만든 값이다.
-- ‼️'기타고사' 행 자체는 지우지 않는다(V90). use_yn=FALSE 로 숨겨 뒀을 뿐이고,
--   과거 상품·매출이 그 값을 쓰고 있어 지우면 집계에서 빠진다.
UPDATE products
   SET sales_division = '기타'
 WHERE cat_code = 'S2026Y02'
   AND (sales_division IS NULL OR sales_division = '' OR sales_division = '기타고사');
