-- 매출 ↔ DSRE 주문 연결. 근거: 프론트 요청(2026-09-18) —
--   "출고번호 · 매출번호 | 응답에 키 자체가 없습니다. 화면의 마지막 컬럼입니다."
--   방향 확인도 받았다: "매출에 주문번호 칸을 두고 등록 시점부터 기록, 과거분은 잇지 않음".
--
-- ★왜 bulk_import_key 로는 안 되는가
--   거기에 주문번호가 들어 있긴 하다(`req_cd:lst_cd:dtl_cd:req_gn` / `DUFF:...:req_cd:...`).
--   하지만 **문자열 안에 섞여 있어** 조인도 색인도 못 한다. 형식도 두 가지다.
--   멱등 dedup 용으로 만든 값이라 조회 축으로 쓰면 형식이 바뀌는 순간 조용히 깨진다.
--
-- ★과거 건은 채우지 않는다. 확인받은 방향이고, 문자열을 파싱해 소급하면
--   형식이 다른 두 종류를 추측으로 갈라야 한다 — 틀리면 남의 주문에 매출이 붙는다.

ALTER TABLE sales
    ADD COLUMN req_cd INT NULL COMMENT 'DSRE2 주문번호(REQ_CD). 주문에서 생성된 매출만. 일반 매출은 NULL';

-- "이 주문이 무슨 매출이 됐나"가 유일한 조회 방향이다(주문 목록에서 역참조).
CREATE INDEX ix_sales_req_cd ON sales (req_cd);
