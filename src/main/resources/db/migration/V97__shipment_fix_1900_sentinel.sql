-- 발송 날짜 세 칸의 **가짜 1900-01-01** 을 비운다.
--
-- 근거: 프론트 실측 2026-10-22 ②-2 — 작업결과·작업요청서의 발송일이 대부분 1900-01-01 이고,
--   '완료' 표시가 사실상 전건 켜져 있었다(2026년 1,878건 중 1,877건).
--
-- ★레거시 원본을 직접 확인했다(로컬 복원 MSSQL, DSLab.sendData 38,578건):
--     printDate     빈값 13,775   값있음 24,803   **1900 = 0건**
--     completeDate  빈값 38,565   값있음     13   **1900 = 0건**
--     sendDate      빈값 21,260                   **1900 = 0건**
--   레거시에는 1900 이 **한 건도 없다.** 비어 있던 칸을 우리 이관이 1900-01-01 로 채웠다.
--
-- ‼️그 값이 null 이 아니어서 `completedAt != null` 이 참이 됐고,
--   **완료가 전건 true** 가 됐다(46,218 / 46,234). 레거시에서 실제로 완료된 건은 13건뿐이다.
--   날짜가 틀린 정도가 아니라 **상태가 통째로 뒤집혀** 있었다.
--
-- 고친 뒤 분포(개발 DB 실측, 삭제 제외 46,236건):
--     발송일 있음(발송완료)            16,888
--     출력O·발송일X(발송준비중)        10,479
--     그 외(출력 전)                   18,869
--     삭제(isDelete=1)                  2,525
--
-- ★진행상태 6단계의 '삭제'는 이미 들어와 있다 — 레거시 isDelete 를 deleted_at 으로 옮겼다.
--
-- 새로 만든 DB 에서는 해당 행이 없어 아무 일도 하지 않는다(멱등).
UPDATE shipment SET printed_at = NULL    WHERE DATE(printed_at) = '1900-01-01';
UPDATE shipment SET completed_at = NULL  WHERE DATE(completed_at) = '1900-01-01';
UPDATE shipment SET sent_date = NULL     WHERE sent_date = '1900-01-01';
